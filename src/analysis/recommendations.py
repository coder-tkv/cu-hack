def _evidences(f: dict) -> list[dict]:
    """Доказательства находки: своей или всех её эпизодов, если она склеена."""
    if f.get("episodes"):
        return [e.get("evidence") or {} for e in f["episodes"]]
    return [f.get("evidence") or {}]


def _enrich_missing_cli(rec: dict, group: list[dict]) -> None:
    binaries = []
    for f in group:
        for ev in _evidences(f):
            b = ev.get("binary")
            if b and b not in binaries:
                binaries.append(b)
    lines = ["## Инструменты, которых не хватало", ""]
    for b in binaries:
        hint = KNOWN_CLI.get(b, "проверьте, нужен ли он вообще, и чем его заменить")
        lines.append(f"- `{b}` — {hint}")
    lines += ["", "_Список собран по ошибкам «command not found» в логе сессии._"]
    rec["content"] = "\n".join(lines) + "\n"
    rec["tools"] = binaries


def _enrich_denied(rec: dict, group: list[dict]) -> None:
    prefixes, tools = [], []
    for f in group:
        for ev in _evidences(f):
            for t in ev.get("tools") or []:
                if t not in tools:
                    tools.append(t)
            for cmd in ev.get("commands") or []:
                if not isinstance(cmd, str):
                    continue
                head = " ".join(cmd.split()[:2])
                if head and head not in prefixes:
                    prefixes.append(head)
    allow = [f"Bash({p}:*)" for p in prefixes[:6]] or [t for t in tools[:6]]
    snippet_json = json.dumps({"permissions": {"allow": allow}}, ensure_ascii=False, indent=2)
    rec["content"] = (
        "## Разрешения\n\n"
        "Черновик для `.claude/settings.json` — проверьте шаблоны перед тем, как разрешать:\n\n"
        f"```json\n{snippet_json}\n```\n\n"
        "_Собрано по вызовам, которые были отклонены в логе сессии._\n"
    )
    rec["tools"] = tools


def _enrich_bash(rec: dict, group: list[dict]) -> None:
    missing = []
    for f in group:
        for ev in _evidences(f):
            if ev.get("tool") and not ev.get("toolUsedInSession"):
                missing.append(ev["tool"])
    if missing:
        rec["action"] += (
            " Проверьте, подключены ли инструменты: "
            + ", ".join(sorted(set(missing)))
            + " — в сессии они ни разу не вызывались."
        )
    rec["tools"] = sorted({ev.get("tool") for f in group for ev in _evidences(f) if ev.get("tool")})


ENRICHERS = {
    "missing_cli": _enrich_missing_cli,
    "tool_permission_denied": _enrich_denied,
    "bash_instead_of_tool": _enrich_bash,
}


def _examples(findings: list[dict], limit: int = 3) -> list[dict]:
    """Конкретика из лога: на что именно ссылается рекомендация."""
    out = []
    for f in findings[:limit]:
        e = f.get("evidence") or {}
        out.append({
            "findingId": f.get("id"),
            "title": f.get("title"),
            "stepIds": f.get("stepIds", [])[:6],
            "detail": snippet(
                e.get("argsPreview") or e.get("errorSnippet") or e.get("filePath")
                or e.get("signature") or (e.get("messages") or [{}])[0].get("text"),
                160,
            ),
        })
    return out


def build_recommendations(findings: list[dict]) -> list[dict]:
    """Одна рекомендация на тип находки, со ссылками на все находки этого типа."""
    by_type: dict[str, list[dict]] = {}
    for f in findings:
        by_type.setdefault(f.get("type"), []).append(f)

    recs: list[dict] = []
    for ftype in TEMPLATES:
        group = by_type.get(ftype)
        if not group:
            continue
        tpl = TEMPLATES[ftype]
        rec = {
            "id": f"r{len(recs) + 1}",
            "findingId": group[0].get("id"),          # основная находка
            "findingIds": [f.get("id") for f in group],
            "findingType": ftype,
            "artifactType": tpl["artifactType"],
            "filename": tpl.get(
                "filename", "CLAUDE.md" if tpl["artifactType"] == CLAUDE_MD else "review-notes.md"
            ),
            "title": tpl["title"],
            "action": tpl["action"],
            "rationale": tpl["rationale"] + f" Затронуто эпизодов: {len(group)}.",
            "verify": tpl["verify"],
            "content": tpl["rule"],
            "examples": _examples(group),
            "source": "code",
        }
        enrich = ENRICHERS.get(ftype)
        if enrich:
            enrich(rec, group)
        recs.append(rec)

    skill = _skill_draft(by_type)
    if skill:
        recs.append(skill)

    for i, r in enumerate(recs, start=1):
        r["id"] = f"r{i}"
    for f in findings:
        f["recommendationId"] = next(
            (r["id"] for r in recs if f.get("id") in r["findingIds"]), None
        )
    return recs


SKILL_NAME = "project-commands"
SKILL_FILENAME = f".claude/skills/{SKILL_NAME}/SKILL.md"


def _skill_draft(groups: dict[str, list[dict]]) -> dict | None:
    """Черновик скилла — третий формат готового файла, который просит кейс."""
    relevant = [t for t in SKILL_TRIGGER_TYPES if groups.get(t)]
    if not relevant:
        return None
    finding_ids = [f["id"] for t in relevant for f in groups[t]]
    commands = []
    for t in relevant:
        for f in groups[t]:
            cmd = (f.get("evidence") or {}).get("argsPreview")
            if cmd and cmd not in commands:
                commands.append(snippet(cmd, 80))
    observed = "\n".join(f"- `{c}`" for c in commands[:5]) or "- (команды не определены)"

    body = (
        f"---\n"
        f"name: {SKILL_NAME}\n"
        "description: Запуск команд этого проекта: как узнать доступные команды и что делать при падении. "
        "Использовать перед первым запуском тестов, сборки или сервера в этом репозитории.\n"
        "---\n\n"
        "# Команды проекта\n\n"
        "## Перед первым запуском\n\n"
        "1. Посмотри, какие команды проект действительно поддерживает: `package.json` (поле scripts), "
        "`Makefile`, `pyproject.toml`, README.\n"
        "2. Запусти ту, что там описана, а не ту, которая кажется стандартной.\n\n"
        "## Если команда упала\n\n"
        "1. Прочитай сообщение об ошибке целиком.\n"
        "2. Назови причину одним предложением.\n"
        "3. Устрани причину и только после этого запускай снова.\n"
        "4. Не запускай ту же команду третий раз без изменений — вместо этого спроси.\n\n"
        "## Что уже наступало на этом проекте\n\n"
        f"{observed}\n\n"
        "_Черновик собран автоматически по разбору сессии. Проверьте команды и допишите под проект._\n"
    )
    return {
        "artifactType": SKILL,
        "filename": SKILL_FILENAME,
        "title": "Черновик скилла: запуск команд проекта",
        "action": f"Положите черновик в {SKILL_FILENAME} и допишите под свой проект.",
        "rationale": "В сессии были повторные запуски и падения команд проекта.",
        "verify": "В следующей сессии перед первым запуском команды должен быть шаг чтения конфигурации проекта.",
        "content": body,
        "findingIds": finding_ids,
        "findingId": finding_ids[0],
        "findingType": relevant[0],
        "examples": _examples([f for t in relevant for f in groups[t]]),
        "source": "code",
    }


def build_claude_md(recommendations: list[dict], meta: dict | None = None) -> str:
    """Готовый CLAUDE.generated.md: только правила для файла проекта."""
    meta = meta or {}
    lines = [
        "# Предлагаемые правила для CLAUDE.md",
        "",
        "Собрано автоматически по разбору одной сессии агента. Просмотрите и перенесите "
        "подходящие пункты в `CLAUDE.md` проекта — файл проекта мы не перезаписываем.",
        "",
    ]
    if meta.get("cwd"):
        lines += [f"Проект: `{meta['cwd']}`", ""]
    patches = [r for r in recommendations if r["artifactType"] == CLAUDE_MD]
    skills = [r for r in recommendations if r["artifactType"] == SKILL]
    if not patches:
        lines.append("Правил для CLAUDE.md по этой сессии не предлагается.")
    for r in patches:
        lines += [r["content"], "", f"_Основание: {r['rationale']} Как проверить: {r['verify']}_", ""]
    setups = [r for r in recommendations if r["artifactType"] == TOOL_SETUP]
    if setups:
        lines += ["---", "", "## Инструменты и доступы", ""]
        for r in setups:
            lines += [f"**{r['title']}** (`{r['filename']}`)", "", r["content"], ""]
    if skills:
        lines += ["---", "", "## Отдельным файлом предлагается черновик скилла", ""]
        for r in skills:
            lines += [f"- `{r['filename']}` — {r['title']}. {r['action']}"]
        lines.append("")
    notes = [r for r in recommendations if r["artifactType"] == RULE]
    if notes:
        lines += ["---", "", "## Заметки для разбора (не правила агента)", ""]
        for r in notes:
            lines += [f"- **{r['title']}.** {r['action']} _{r['rationale']}_"]
    return "\n".join(lines).rstrip() + "\n"
